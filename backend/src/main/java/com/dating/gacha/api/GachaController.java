package com.dating.gacha.api;

import com.dating.common.security.AuthenticatedUser;
import com.dating.gacha.application.GachaService;
import jakarta.validation.Valid;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.web.bind.annotation.*;

import java.util.List;

/**
 * Gacha for users: banners with disclosed rates, pulls (paid with the banner's cost item, GACHA_TICKET by default),
 * history and the duplicate-shards exchange.
 */
// Hidden for now in favour of interest groups (docs/communities.md); data and the admin API are kept.
@ConditionalOnProperty(prefix = "app.gacha", name = "enabled", havingValue = "true")
@RestController
@RequestMapping("/api/v1/gacha")
public class GachaController {

    /**
     * @param count          1 or the banner's multi-pull size (10 by default)
     * @param idempotencyKey generated by the client per pull action; a retry with the same key returns the same results
     */
    public record PullRequest(
            @NotNull(message = "Укажите количество круток") @Min(value = 1, message = "От 1") @Max(value = 100, message = "Не больше 100")
            Integer count,
            @NotBlank(message = "Укажите ключ запроса") @Size(max = 100, message = "Не длиннее 100 символов")
            String idempotencyKey) {
    }

    public record ExchangeRequest(
            @NotNull(message = "Укажите количество билетов") @Min(value = 1, message = "От 1") Integer tickets,
            @NotBlank(message = "Укажите ключ запроса") @Size(max = 100, message = "Не длиннее 100 символов")
            String idempotencyKey) {
    }

    private final GachaService gachaService;

    public GachaController(GachaService gachaService) {
        this.gachaService = gachaService;
    }

    @GetMapping("/banners")
    public ResponseEntity<List<BannerDto>> banners(@AuthenticationPrincipal AuthenticatedUser user) {
        return ResponseEntity.ok(gachaService.openBanners(user.accountId()));
    }

    @GetMapping("/banners/{code}")
    public ResponseEntity<BannerDto> banner(@AuthenticationPrincipal AuthenticatedUser user, @PathVariable String code) {
        return ResponseEntity.ok(gachaService.banner(user.accountId(), code));
    }

    @PostMapping("/banners/{code}/pull")
    public ResponseEntity<PullResponseDto> pull(@AuthenticationPrincipal AuthenticatedUser user,
                                                @PathVariable String code,
                                                @Valid @RequestBody PullRequest request) {
        return ResponseEntity.ok(gachaService.pull(user.accountId(), code, request.count(), request.idempotencyKey()));
    }

    @GetMapping("/history")
    public ResponseEntity<HistoryPageDto> history(@AuthenticationPrincipal AuthenticatedUser user,
                                                  @RequestParam(required = false, defaultValue = "20") int limit,
                                                  @RequestParam(required = false) Long before) {
        return ResponseEntity.ok(gachaService.history(user.accountId(), before, limit));
    }

    @GetMapping("/shards")
    public ResponseEntity<ShardsDto> shards(@AuthenticationPrincipal AuthenticatedUser user) {
        return ResponseEntity.ok(gachaService.shards(user.accountId()));
    }

    @PostMapping("/shards/exchange")
    public ResponseEntity<ShardExchangeResultDto> exchange(@AuthenticationPrincipal AuthenticatedUser user,
                                                           @Valid @RequestBody ExchangeRequest request) {
        return ResponseEntity.ok(gachaService.exchangeShards(user.accountId(), request.tickets(),
                request.idempotencyKey()));
    }
}
