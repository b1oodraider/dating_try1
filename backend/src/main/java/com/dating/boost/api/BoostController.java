package com.dating.boost.api;

import com.dating.boost.application.BoostService;
import com.dating.common.security.AuthenticatedUser;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * Profile boost: the owner's status and activation. See docs/boost.md.
 */
@RestController
@RequestMapping("/api/v1/me/boost")
public class BoostController {

    /**
     * @param idempotencyKey generated by the client once per tap; a retry with the same key never spends twice
     */
    public record ActivateRequest(
            @NotBlank(message = "Укажите ключ идемпотентности")
            @Size(max = 100, message = "Ключ идемпотентности длиннее 100 символов")
            String idempotencyKey) {
    }

    private final BoostService boostService;

    public BoostController(BoostService boostService) {
        this.boostService = boostService;
    }

    @GetMapping
    public ResponseEntity<BoostStatusDto> status(@AuthenticationPrincipal AuthenticatedUser user) {
        return ResponseEntity.ok(boostService.status(user.accountId()));
    }

    @PostMapping
    public ResponseEntity<BoostStatusDto> activate(@AuthenticationPrincipal AuthenticatedUser user,
                                                   @Valid @RequestBody ActivateRequest request) {
        return ResponseEntity.ok(boostService.activate(user.accountId(), request.idempotencyKey().trim()));
    }
}
